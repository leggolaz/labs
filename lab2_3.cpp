#include <iostream>                          // нужен для cout

int SumTo(int n = 1)                         // считает сумму от 1 до n; если число не дали, n будет 1
{                                            // открываем функцию
    int result = 0;                          // сюда копим сумму, начинаем с нуля
    if (n <= 0)                              // если число 0 или меньше нуля
    {                                        // открываем if
        return 0;                            // по заданию в этом случае отдаём 0 и выходим
    }                                        // закрываем if
    for (int i = 1; i <= n; i++)             // идём от 1 до n
    {                                        // открываем for
        result = result + i;                 // добавляем текущее число к сумме
    }                                        // закрываем for
    return result;                           // отдаём готовую сумму туда, откуда вызвали
}                                            // закрываем функцию

void Calc(int a, int b, int& sum, int& mult) // a и b просто копии, а sum и mult со знаком & это настоящие переменные снаружи
{                                            // открываем функцию
    sum = a + b;                             // кладём сумму прямо в переменную снаружи
    mult = a * b;                            // кладём произведение прямо в переменную снаружи
}                                            // закрываем функцию

int main()                                   // начало программы
{                                            // открываем main
    int a[2][3] = { { 1, 2, 3 },{ 4, 5, 6 } };    // таблица: 2 строки, 3 столбца

    int total = 0;                           // сумма всех чисел таблицы, начинаем с нуля
    for (int i = 0; i < 2; i++)              // i это номер строки (0 и 1)
    {                                        // открываем внешний for
        for (int j = 0; j < 3; j++)          // j это номер столбца (0, 1, 2)
        {                                    // открываем внутренний for
            total = total + a[i][j];         // берём число из ячейки и добавляем к сумме
        }                                    // закрываем внутренний for
    }                                        // закрываем внешний for
    std::cout << "Сумма всех чисел: " << total << std::endl;  // печатаем общую сумму (21)

    int b[3] = { 0, 0, 0 };                    // маленький массив для сумм столбцов, пока одни нули
    for (int j = 0; j < 3; j++)              // тут сначала идём по столбцам
    {                                        // открываем внешний for
        for (int i = 0; i < 2; i++)          // а внутри по строкам, то есть идём вниз по столбцу
        {                                    // открываем внутренний for
            b[j] = b[j] + a[i][j];           // добавляем число из столбца j в ячейку b[j]
        }                                    // закрываем внутренний for
    }                                        // закрываем внешний for

    for (int j = 0; j < 3; j++)              // идём по массиву сумм столбцов
    {                                        // открываем for
        std::cout << b[j] << " ";            // печатаем число и пробел (получится 5 7 9)
    }                                        // закрываем for
    std::cout << std::endl;                  // новая строка

    float x = 20.84f;                        // обычная переменная; f в конце нужна, чтобы число было float
    float& ref1 = x;                         // ref1 это второе имя для x, не копия
    float& ref2 = x;                         // ref2 тоже второе имя для x
    ref1 = 5.5f;                             // меняю через ref1, а поменяется сама x
    std::cout << "x = " << x << std::endl;           // x стала 5.5
    std::cout << "ref1 = " << ref1 << std::endl;     // ref1 тоже 5.5
    std::cout << "ref2 = " << ref2 << std::endl;     // ref2 тоже 5.5, значит все три это одна и та же переменная

    std::cout << "SumTo(5) = " << SumTo(5) << std::endl;  // даю 5, получаю 1+2+3+4+5 = 15
    std::cout << "SumTo() = " << SumTo() << std::endl;    // ничего не даю, берётся 1 по умолчанию, ответ 1

    int s = 0;                               // сюда функция положит сумму
    int m = 0;                               // сюда функция положит произведение
    std::cout << "До вызова: s = " << s << ", m = " << m << std::endl;     // пока обе равны 0
    Calc(3, 4, s, m);                        // после этого s будет 7, а m будет 12
    std::cout << "После вызова: s = " << s << ", m = " << m << std::endl;  // видим, что они поменялись

    int v = 100;                             // обычная переменная, значение любое
    std::cout << "v = " << v << std::endl;   // печатаем её

    for (int k = 0; k < 3; k++)              // цикл на 3 повтора (k = 0, 1, 2)
    {                                        // открываем for
        int inner = 7;                       // эта переменная живёт только внутри цикла
        std::cout << "v в цикле = " << v << std::endl;          // v видно и тут, печатается 3 раза
        std::cout << "inner в цикле = " << inner << std::endl;  // inner печатается 3 раза
    }                                        // закрываем for, тут inner исчезает

    // std::cout << inner << std::endl;      // если раскомментировать, будет ошибка: за пределами цикла inner не видно

    return 0;                                // всё прошло нормально
}                                            // закрываем main