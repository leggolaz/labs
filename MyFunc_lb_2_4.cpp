#include <iostream>                          // нужен для cout и endl
#include "MyFunc.h"                          // подключаем свой .h; свои файлы в кавычках, а не в <>
using namespace std;                         // пункт 4: из-за этой строки ниже пишу cout и endl без std::

namespace MyFuncs                            // открываем ту же "папку", что и в .h
{                                            // открываем namespace
    void ShowSum(int x)                      // тут уже сама функция со всем кодом
    {                                        // открываем функцию
        static int last = 0;                 // static значит переменная создаётся один раз и помнит значение между вызовами
        cout << x + last << endl;            // печатаем сумму: число сейчас + число с прошлого раза
        last = x;                            // запоминаем число, чтобы использовать в следующий раз
    }                                        // закрываем функцию
}                                            // закрываем namespace