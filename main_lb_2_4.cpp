#include <iostream>                          // нужен для cout
#include "MyFunc.h"                          // без этого main не узнает про ShowSum

#define SUM(a, b) ((a) + (b))                // макрос: просто подставляет текст, скобки нужны, чтобы не ломался порядок вычислений

int main()                                   // начало программы
{                                            // открываем main
    MyFuncs::ShowSum(5);                     // первый вызов: 5 + 0 = 5, запомнили 5
    MyFuncs::ShowSum(10);                    // второй вызов: 10 + 5 = 15, запомнили 10
    MyFuncs::ShowSum(3);                     // третий вызов: 3 + 10 = 13, запомнили 3

    std::cout << SUM(2, 3) << std::endl;     // макрос превратится в ((2) + (3)), выведет 5

    return 0;                                // всё прошло нормально
}                                            // закрываем main